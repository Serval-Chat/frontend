export function getGodboltLanguageId(displayLanguage: string): string | null {
    const key = displayLanguage.toLowerCase().trim();
    if (GODBOLT_EXCLUDED_LANGUAGES.has(key)) return null;
    return GODBOLT_LANGUAGE_MAP[key] ?? null;
}

