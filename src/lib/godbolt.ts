function encodeBase64Utf8(str: string): string {
    const bytes = new TextEncoder().encode(str);
    const binString = Array.from(bytes, (byte) => String.fromCharCode(byte)).join('');
    return btoa(binString);
}

export function buildGodboltUrl(code: string, languageId: string): string {
    const compilerId = GODBOLT_DEFAULT_COMPILER[languageId];
    const options = GODBOLT_DEFAULT_OPTIONS[languageId] ?? '';

    if (!compilerId) {
        const clientState = {
            sessions: [{ id: 1, language: languageId, source: code, compilers: [], executors: [] }],
        };
        const encoded = encodeBase64Utf8(JSON.stringify(clientState));
        return `https://godbolt.org/clientstate/${encoded}`;
    }

    const clientState = {
        sessions: [
            {
                id: 1,
                language: languageId,
                source: code,
                compilers: [
                    {
                        id: compilerId,
                        options,
                        filters: {
                            intel: true,
                            demangle: true,
                            commentOnly: true,
                            directives: false,
                            labels: false,
                            trim: false,
                            binary: false,
                            binaryObject: false,
                            execute: false,
                            libraryCode: false,
                        },
                    },
                ],
                executors: [
                    {
                        compiler: {
                            id: compilerId,
                            options,
                            libs: [],
                        },
                        stdin: '',
                        stdinVisible: false,
                        args: '',
                        runtimeTools: [],
                    },
                ],
            },
        ],
    };

    const encoded = encodeBase64Utf8(JSON.stringify(clientState));
    return `https://godbolt.org/clientstate/${encoded}`;
}

